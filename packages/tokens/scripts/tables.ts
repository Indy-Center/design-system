import type { Plugin } from "@terrazzo/parser";

/**
 * Writes tables.md: the brand guide's two tables (brand colours; roles),
 * each between markers, to paste into brand-guide/guide/color-and-type.md.
 * Names and order come from the token files: brand colours from the
 * resolver's `brand` set, roles from its `theme` modifier. "Used for" is
 * each token's $description.
 */
export default function tables({
  filename = "tables.md",
}: { filename?: string } = {}): Plugin {
  return {
    name: "indy-center:tables",
    enforce: "post",
    async build({ resolver, outputFile }) {
      const light = resolver.apply({ theme: "light" });
      const dark = resolver.apply({ theme: "dark" });
      const brandNames = colourNames(resolver.source.sets?.brand?.sources);
      const roleNames = colourNames(
        resolver.source.modifiers?.theme?.contexts?.light,
      );

      const hex = (set: typeof light, name: string) => {
        const token = set[`color.${name}`];
        if (token?.$type !== "color" || !token.$value.hex) {
          throw new Error(`color.${name}: no hex to print`);
        }
        return `\`${token.$value.hex.toUpperCase()}\``;
      };
      const usedFor = (name: string) => light[`color.${name}`]?.$description;

      const brandRows = brandNames.map(
        (name) =>
          `| ${name[0]!.toUpperCase()}${name.slice(1)} | ${hex(light, name)} | ${usedFor(name)} |`,
      );
      const roleRows = roleNames.map(
        (name) =>
          `| \`${name}\` | ${usedFor(name)} | ${hex(light, name)} | ${hex(dark, name)} |`,
      );

      outputFile(
        filename,
        [
          "<!-- Generated by @indy-center/tokens from its token files. Paste each table between the same markers in the brand guide. -->",
          "",
          "<!-- brand-colours:start -->",
          "| Name | Hex | Used for |",
          "| --- | --- | --- |",
          ...brandRows,
          "<!-- brand-colours:end -->",
          "",
          "<!-- roles:start -->",
          "| Role | Used for | Light | Dark |",
          "| --- | --- | --- | --- |",
          ...roleRows,
          "<!-- roles:end -->",
          "",
        ].join("\n"),
      );
    },
  };
}

/** The colour token names in a resolver source list, in file order. */
function colourNames(sources: unknown): string[] {
  if (!Array.isArray(sources)) return [];
  return sources.flatMap((source) =>
    Object.keys(source?.color ?? {}).filter((key) => !key.startsWith("$")),
  );
}
